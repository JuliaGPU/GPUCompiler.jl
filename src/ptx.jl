## target

export PTXCompilerTarget

Base.@kwdef struct PTXCompilerTarget <: AbstractCompilerTarget
    cap::VersionNumber
    ptx::VersionNumber = v"6.0" # for compatibility with older versions of CUDA.jl

    # subtarget feature set, selecting the suffix on the LLVM CPU name (and `.target`):
    #   :baseline (no suffix)   - forward-compatible (sm_X for any sm_Y >= X)
    #   :family   ('f' suffix)  - same-major-family-portable; gates 'f'-tier intrinsics
    #   :arch     ('a' suffix)  - locked to one exact CC; unlocks all arch-accel intrinsics
    feature_set::Symbol = :baseline

    # codegen quirks
    ## can we emit debug info in the PTX assembly?
    debuginfo::Bool = false

    # optional properties
    minthreads::Union{Nothing,Int,NTuple{<:Any,Int}} = nothing
    maxthreads::Union{Nothing,Int,NTuple{<:Any,Int}} = nothing
    blocks_per_sm::Union{Nothing,Int} = nothing
    maxregs::Union{Nothing,Int} = nothing

    fastmath::Bool = Base.JLOptions().fast_math == 1

    # can system-scope atomics be used? the ISA supports them from sm_60 on (which
    # `validate_ir` checks separately), but some platforms reject them, e.g. Pascal GPUs
    # under Windows, or Tegra GPUs before sm_72.
    system_atomics::Bool = true

    # deprecated; remove with next major version
    exitable::Union{Nothing,Bool} = nothing
    unreachable::Union{Nothing,Bool} = nothing
end

function Base.hash(target::PTXCompilerTarget, h::UInt)
    h = hash(target.cap, h)
    h = hash(target.ptx, h)
    h = hash(target.feature_set, h)

    h = hash(target.debuginfo, h)

    h = hash(target.minthreads, h)
    h = hash(target.maxthreads, h)
    h = hash(target.blocks_per_sm, h)
    h = hash(target.maxregs, h)
    h = hash(target.fastmath, h)
    h = hash(target.system_atomics, h)

    h
end

# format the LLVM CPU / PTX `.target` name for this target
function cpu_name(target::PTXCompilerTarget)
    suffix = target.feature_set === :arch    ? "a" :
             target.feature_set === :family  ? "f" :
             target.feature_set === :baseline ? "" :
             error("PTXCompilerTarget.feature_set must be one of :baseline, :family, :arch; got $(repr(target.feature_set))")
    return "sm_$(target.cap.major)$(target.cap.minor)$suffix"
end

source_code(target::PTXCompilerTarget) = "ptx"

llvm_triple(target::PTXCompilerTarget) = Int===Int64 ? "nvptx64-nvidia-cuda" : "nvptx-nvidia-cuda"


function llvm_machine(target::PTXCompilerTarget)
    @static if :NVPTX ∉ LLVM.backends()
        return nothing
    end
    triple = llvm_triple(target)
    t = LLVM.Target(triple=triple)

    # this machine only drives the middle end; machine code is generated by an external,
    # up-to-date back-end that sees the true target. as the in-process LLVM may not even
    # know the targeted device (unknown CPUs noisily degrade to the sm_20 subtarget),
    # use the generic subtarget: subtarget-dependent middle-end behavior is handled by
    # GPUCompiler itself (`nvvm_reflect!`), and differences in cost models are immaterial.
    return LLVM.TargetMachine(t, triple)
end

# match the layout computed by the NVPTX back-end (computeNVPTXDataLayout); components
# that match LLVM's defaults (small integers, floats, common vectors) are left implicit.
# note that the external back-end ignores the module datalayout and recomputes it from
# the target, so the middle end needs to match it exactly, or offsets folded early would
# disagree with the final layout. this notably affects i128, which Julia did not even
# align to 16 bytes before 1.12 (users may have to reject affected types, as kernel
# argument layouts will differ between such hosts and the device).
llvm_datalayout(target::PTXCompilerTarget) =
    # little endian
    "e-" *
    # on 32-bit systems, use 32-bit pointers, including for distributed shared
    # memory (addrspace 7). on 64-bit systems, use 64-bit pointers (the default).
    (Int === Int64 ? "" :  "p:32:32-p7:32:32-") *
    # tensor memory (addrspace 6) always uses 32-bit pointers
    "p6:32:32-" *
    # alignment of integer types
    "i64:64-i128:128-i256:256-" *
    # alignment of vector types
    "v16:16-v32:32-" *
    # native integer widths
    "n16:32:64"

have_fma(@nospecialize(target::PTXCompilerTarget), T::Type) = true

dwarf_version(target::PTXCompilerTarget) = Int32(2) # Cuda only supports dwarfv2

can_vectorize(job::CompilerJob{PTXCompilerTarget}) = true

# NVPTX knows `block`, `cluster` and `device`. PTX has no scope for a warp, so use the block
# one for subgroups, like Clang does.
llvm_syncscope(::PTXCompilerTarget, name::String) =
    name in ("subgroup", "workgroup") ? "block" : name

