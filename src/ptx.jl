    end
end


## validation

# Atomic operations and fences come from many front-ends (CUDA.jl's atomic functions,
# UnsafeAtomics and Atomix, Enzyme, Julia's atomic intrinsics), so they are validated here,
# on the IR, rather than in any of them. The NVPTX back-end does not reject everything the
# target cannot run: it silently drops a system scope before sm_60, emits PTX that `ptxas`
# or the driver reject, or aborts the process. Validation runs after `lower_syncscopes!`, so
# the scopes are the ones NVPTX knows.
function validate_ir(job::CompilerJob{PTXCompilerTarget}, mod::LLVM.Module)
    errors = IRError[]
    dl = mod.datalayout
    for f in mod.functions, bb in f.blocks, inst in bb.instructions
        reason = if is_atomic_memop(inst)
            ptx_atomic_error(job, dl, inst)
        elseif inst isa LLVM.FenceInst
            ptx_syncscope_error(inst, "fence")
        else
            nothing
        end
        reason === nothing || push!(errors, (reason, backtrace(inst), string(inst)))
    end
    return errors
end

# the synchronization scopes of NVPTX, as `lower_syncscopes!` leaves them. a cluster is a
# single block on targets without clusters, where NVPTX uses the block scope instead.
const PTX_SYNCSCOPES = ("singlethread", "block", "cluster", "device", "system")

ptx_syncscope_error(@nospecialize(inst::LLVM.Instruction), what="atomic operation") =
    inst.syncscope.name in PTX_SYNCSCOPES ? nothing :
    "$what with synchronization scope $(repr(inst.syncscope.name))"

# Why the target cannot run the atomic memory operation `inst`, or `nothing` if it can.
# Operations PTX has no instruction for (e.g. 8- and 16-bit read-modify-writes, most
# floating-point ones, or `fadd` on older devices) are fine: NVPTX expands them to
# compare-exchange loops.
function ptx_atomic_error(@nospecialize(job::CompilerJob{PTXCompilerTarget}),
                          dl::LLVM.DataLayout, @nospecialize(inst::LLVM.Instruction))
    target = job.config.target
    reason = ptx_syncscope_error(inst)
    reason === nothing || return reason
    system = inst.syncscope.name == "system"

    as = inst.pointer_operand.value_type.addrspace
    if !(as in (0, 1, 3, 7))
        return "atomic operation in address space $as (PTX only supports atomics on generic, global and shared memory)"
    end
    if as == 7 && (target.cap < v"9.0" || target.ptx < v"7.8")
        return "atomic operation on shared::cluster memory (requires compute capability 9.0 and PTX ISA 7.8)"
    end

    # (vectors aren't supported either: integer vectors crash NVPTX 23.1, and PTX only has
    # vector atomics for a few floating-point reductions)
    T = atomic_value_type(inst)
    bits = if T isa LLVM.IntegerType || T isa LLVM.FloatingPointType || T isa LLVM.PointerType
        Int(LLVM.bit_size(dl, T))
    end
    if !(bits in (8, 16, 32, 64) || (bits == 128 && T isa LLVM.IntegerType))
        return "atomic operation on a $(string(T)) value"
    end
    if bits == 128
        if target.cap < v"9.0" || target.ptx < v"8.3"
            return "128-bit atomic operation (requires compute capability 9.0 and PTX ISA 8.3)"
        end
        # (NVPTX emits `.sys` 128-bit atomics with PTX ISA 8.3, which `ptxas` rejects)
        if system && target.ptx < v"8.4"
            return "system-scope 128-bit atomic operation (requires PTX ISA 8.4)"
        end
    end
    if inst.alignment < bits ÷ 8
        return "atomic operation with alignment $(inst.alignment) (requires at least $(bits ÷ 8)-byte alignment)"
    end

    # loads and stores only take a scope from sm_70 on (before, they are volatile accesses,
    # bracketed by `membar`s that support every scope), and shared memory is only visible
    # within a block or cluster, so this only concerns read-modify-writes on other memory
    if system && (inst isa LLVM.AtomicRMWInst || inst isa LLVM.AtomicCmpXchgInst) &&
       !(as in (3, 7))
        if target.cap < v"6.0"
            return "system-scope atomic operation (requires compute capability 6.0; use device scope if system-wide atomicity is not required)"
        elseif !target.system_atomics
            return "system-scope atomic operation (not supported on this platform; use device scope if system-wide atomicity is not required)"
        end
    end

    return nvptx_atomic_error(inst)
end

# Why the NVPTX back-end cannot compile the atomic memory operation `inst`, although the
# target supports it, or `nothing` if it can. These work around bugs in the back-end, and
# should be revisited when updating it.
function nvptx_atomic_error(@nospecialize(inst::LLVM.Instruction))
    # NVPTX's instruction printer aborts on the ordering of the `atom.cas.b128` and
    # `atom.exch.b128` that it legalizes these to (LLVM 23.1, and main as of October 2026)
    T = atomic_value_type(inst)
    if (inst isa LLVM.LoadInst || inst isa LLVM.StoreInst) &&
       inst.ordering == LLVM.AtomicOrdering.SequentiallyConsistent &&
       T isa LLVM.IntegerType && T.width == 128
        return "sequentially-consistent 128-bit atomic load or store (not supported by the NVPTX back-end)"
    end
    return nothing
end


## atomics on local memory

# PTX only has atomic instructions, and atomic (relaxed, acquire or release) loads and
# stores, for global and shared memory, and for generic addresses of those. On the stack
# (local memory) they are undefined: Pascal GPUs fail with CUDA_ERROR_INVALID_ADDRESS_SPACE,
# which leaves the context unusable, and ptxas rejects the `atom.local` that NVPTX selects
# for a `cmpxchg` on an `alloca`. NVPTX only demotes `atomicrmw` on pointers it knows to be
# local, and only when optimizing.
#
# Atomics on the stack are common nonetheless, e.g., on objects that Julia's `AllocOpt`
# moved there, or in code from Enzyme, which accumulates into the shadow of an argument with
# an atomic when it cannot see where the argument points, e.g., to a stack slot of the
# caller (Enzyme.jl#428). Since no other thread can access a thread's stack, plain accesses
# behave the same, so `lower_local_atomics!`, like NVIDIA's libcu++:
# - replaces atomics on the thread's own memory by plain accesses;
# - checks at run time whether an atomic on a generic pointer that may point to the stack
#   does, and then performs the plain accesses instead (see `guard_local_atomic!`).
#
# `unordered` loads and stores aren't checked: Julia uses them for every access to a heap
# reference, and NVPTX only lowers them to instructions that local memory doesn't support
# (`ld.relaxed` and `st.relaxed`) from sm_70 on, which hasn't been seen to fail.

# Is `ptr` known to point to the thread's own memory?
ptx_thread_private(@nospecialize(ptr::LLVM.Value)) =
    ptr.value_type.addrspace == #=local=# 5 || is_thread_private(ptr)

# Can `ptr` point to local memory? Generic pointers can, unless every object they can be
# derived from is in another address space.
function ptx_may_be_local(@nospecialize(ptr::LLVM.Value))
    seen = Set{LLVM.Value}()
    worklist = LLVM.Value[ptr]
    while !isempty(worklist)
        val = pop!(worklist)
        val in seen && continue
        push!(seen, val)
        as = val.value_type.addrspace
        if as == #=local=# 5
            return true
        elseif as != #=generic=# 0 || val isa LLVM.GlobalVariable
            continue
        elseif val isa LLVM.GetElementPtrInst || val isa LLVM.BitCastInst ||
               val isa LLVM.AddrSpaceCastInst
            push!(worklist, val.operands[1])
        elseif val isa LLVM.ConstantExpr &&
               val.opcode in (LLVM.Opcode.GetElementPtr, LLVM.Opcode.BitCast,
                              LLVM.Opcode.AddrSpaceCast)
            push!(worklist, val.operands[1])
        elseif val isa LLVM.PHIInst
            append!(worklist, first.(val.incoming))
        elseif val isa LLVM.SelectInst
            push!(worklist, val.operands[2], val.operands[3])
        else
            return true
        end
    end
    return false
end

# Does the `!noalias.addrspace` metadata of `inst` rule out that it accesses local memory?
# `guard_local_atomic!` adds it to the atomic it keeps for other memory.
function excludes_local(@nospecialize(inst::LLVM.Instruction))
    haskey(inst.metadata, "noalias.addrspace") || return false
    md = inst.metadata["noalias.addrspace"]
    bounds = [convert(Int, Value(op)) % UInt32 for op in md.operands]
    # (pairs of half-open ranges, which can wrap around)
    return any(1:2:length(bounds)) do i
        lo, hi = bounds[i], bounds[i+1]
        lo <= hi ? lo <= 5 < hi : (5 >= lo || 5 < hi)
    end
end

# Replace the atomic memory operation `inst` by a call to a function that checks whether
# its pointer points to local memory, and then performs it with plain accesses, or atomically
# otherwise. The function is meant to be inlined (it is `alwaysinline`).
function guard_local_atomic!(@nospecialize(inst::LLVM.Instruction))
    mod = LLVM.parent(LLVM.parent(LLVM.parent(inst)))
    args = collect(inst.operands)
    T = inst.value_type
    ft = LLVM.FunctionType(T, LLVMType[arg.value_type for arg in args])
    f = LLVM.Function(mod, "gpucompiler.local_atomic", ft)
    f.linkage = LLVM.Linkage.Internal
    push!(f.function_attributes, EnumAttribute(:alwaysinline))

    # the operation, on the arguments of the function. the clones would refer to the debug
    # info of the caller, so they get the location of the call when inlined instead.
    local_atomic, other_atomic = copy(inst), copy(inst)
    for clone in (local_atomic, other_atomic)
        clone.debug_location = nothing
        for (i, param) in enumerate(f.parameters)
            clone.operands[i] = param
        end
    end
    other_atomic.metadata["noalias.addrspace"] =
        MDNode(Metadata[ConstantInt(Int32(5)), ConstantInt(Int32(6))])

    isspacep = LLVM.Function(mod, LLVM.Intrinsic("llvm.nvvm.isspacep.local"))
    isspacep_ft = isspacep.function_type
    @dispose builder=IRBuilder() begin
        entry = BasicBlock(f, "entry")
        local_block = BasicBlock(f, "local")
        other_block = BasicBlock(f, "other")
        exit = BasicBlock(f, "exit")

        position!(builder, LLVM.at_end(entry))
        # (the intrinsic takes an `i8*` with typed pointers)
        ptr = f.parameters[inst isa LLVM.StoreInst ? 2 : 1]
        T_ptr = only(isspacep_ft.parameters)
        ptr = ptr.value_type == T_ptr ? ptr : bitcast!(builder, ptr, T_ptr)
        is_local = call!(builder, isspacep_ft, isspacep, [ptr])
        br!(builder, is_local, local_block, other_block)

        for (block, atomic) in ((local_block, local_atomic), (other_block, other_atomic))
            move!(atomic, LLVM.at_end(block))
            position!(builder, LLVM.at_end(block))
            br!(builder, exit)
        end

        position!(builder, LLVM.at_end(exit))
        if T isa LLVM.VoidType
            ret!(builder)
        else
            result = phi!(builder, T)
            append!(result.incoming, Tuple{LLVM.Value,BasicBlock}[(local_atomic, local_block),
                                                                  (other_atomic, other_block)])
            ret!(builder, result)
        end
    end
    # (after building the users of its result, which lowering replaces)
    demote_private_atomic!(local_atomic)

    @dispose builder=IRBuilder() begin
        position!(builder, LLVM.before(inst))
        call = call!(builder, ft, f, args)
        call.debug_location = inst.debug_location
        T isa LLVM.VoidType || replace_uses!(inst, call)
    end
    erase!(inst)
    return
end

function lower_local_atomics!(mod::LLVM.Module)
    changed = false
    @tracepoint "lower local atomics" begin

    atomics = LLVM.Instruction[inst for f in mod.functions for bb in f.blocks
                               for inst in bb.instructions if is_atomic_memop(inst)]
    guarded = false
    for inst in atomics
        if ptx_thread_private(inst.pointer_operand)
            demote_private_atomic!(inst)
            changed = true
        elseif (inst isa LLVM.LoadInst || inst isa LLVM.StoreInst) &&
               inst.ordering == LLVM.AtomicOrdering.Unordered
            continue
        elseif ptx_may_be_local(inst.pointer_operand) && !excludes_local(inst)
            guard_local_atomic!(inst)
            changed = guarded = true
        end
    end

    # inline the checks (the pass removes the functions)
    if guarded
        @dispose pb=PassBuilder() begin
            add!(pb, AlwaysInlinerPass())
            run!(pb, mod)
        end
    end

    end
    return changed
end


## LLVM passes

# Replace occurrences of __nvvm_reflect("foo") and llvm.nvvm.reflect with an integer.
#
# This matches LLVM's NVVMReflectPass: `__CUDA_ARCH` is derived from the target
# capability, `__CUDA_FTZ` is read from the `nvvm-reflect-ftz` module flag, and every
# other key folds to 0. Knobs like denormal flushing or FMAD contraction must be
# configured through module flags or LLVM fast-math flags, not here.
const NVVM_REFLECT_FUNCTION = "__nvvm_reflect"
function nvvm_reflect!(@nospecialize(job::CompilerJob), mod::LLVM.Module)
    changed = false
    @tracepoint "nvvmreflect" begin

    # find and sanity check the nnvm-reflect function
    # TODO: also handle the llvm.nvvm.reflect intrinsic
    reflect_function = get(mod.functions, NVVM_REFLECT_FUNCTION, nothing)
    reflect_function === nothing && return false
    isdeclaration(reflect_function) || error("_reflect function should not have a body")
    reflect_typ = reflect_function.function_type.return_type
    isa(reflect_typ, LLVM.IntegerType) || error("_reflect's return type should be integer")

    # pull __CUDA_FTZ from the nvvm-reflect-ftz module flag (same source LLVM uses)
    ftz_val = 0
    if haskey(mod.flags, "nvvm-reflect-ftz")
        flag = mod.flags["nvvm-reflect-ftz"]
        if flag isa LLVM.ConstantAsMetadata
            c = LLVM.Value(flag)
            if c isa ConstantInt
                ftz_val = Int(convert(Int64, c))
            end
        end
    end

    to_remove = []
    for use in reflect_function.uses
        call = use.user
        isa(call, LLVM.CallInst) || continue
        if length(call.operands) != 2
            @error """Unrecognized format of __nvvm_reflect call:
                      $(string(call))
                      Wrong number of operands: expected 2, got $(length(call.operands))."""
            continue
        end

        # decode the string argument
        if LLVM.version() >= v"17"
            sym = call.operands[1]
        else
            str = call.operands[1]
            if !isa(str, LLVM.ConstantExpr) || str.opcode != LLVM.Opcode.GetElementPtr
                @safe_error """Unrecognized format of __nvvm_reflect call:
                               $(string(call))
                               Operand should be a GEP instruction, got a $(typeof(str)). Please file an issue."""
                continue
            end
            sym = str.operands[1]
            if isa(sym, LLVM.ConstantExpr) && sym.opcode == LLVM.Opcode.GetElementPtr
                # CUDA 11.0 or below
                sym = sym.operands[1]
            end
        end
        if !isa(sym, LLVM.GlobalVariable)
            @safe_error """Unrecognized format of __nvvm_reflect call:
                           $(string(call))
                           Operand should be a global variable, got a $(typeof(sym)). Please file an issue."""
            continue
        end
        sym_op = sym.initializer
        if sym_op === nothing || !isstring(sym_op)
            @safe_error """Unrecognized format of __nvvm_reflect call:
                           $(string(call))
                           Operand should be a constant string, got a $(typeof(sym_op)). Please file an issue."""
            continue
        end
        reflect_arg = chop(String(sym_op))  # without the terminating NUL

        # match LLVM's NVVMReflectPass: unknown keys fold to 0.
        reflect_val = if reflect_arg == "__CUDA_ARCH"
            ConstantInt(reflect_typ,
                        job.config.target.cap.major*100 + job.config.target.cap.minor*10)
        elseif reflect_arg == "__CUDA_FTZ"
            ConstantInt(reflect_typ, ftz_val)
        else
            ConstantInt(reflect_typ, 0)
        end

        replace_uses!(call, reflect_val)
        push!(to_remove, call)
        changed = true
    end

    # remove the calls to the function
    for val in to_remove
        @assert isempty(val.uses)
        erase!(val)
    end

    # maybe also delete the function
    if isempty(reflect_function.uses)
        erase!(reflect_function)
    end

    end
    return changed
end

# The passes below rewrite `afn`-flagged f64 operations to NVPTX' fast lowerings.
# `apply_fastmath!` propagates job-wide `target.fastmath=true` as per-instruction
# `afn`, so a single flag check covers both per-call `@fastmath` and the job toggle.
# We emit NVPTX intrinsics by name (rather than libdevice `__nv_*`) so this doesn't
# depend on which libdevice symbols got linked in.
#
# Only f64 needs this: the back-end natively honors `afn` for f32 fdiv/sqrt/rsqrt
# (selecting the FTZ variants based on the `denormal-fp-math-f32` attribute), but
# lacks fast f64 lowerings. There is no hardware fast f64 div/sqrt, and the f64
# `rsqrt.approx.d` instruction is not selected for `1/sqrt(x)` upstream (NVPTX'
# `getSqrtEstimate` does not consult per-instruction `afn`, only the
# "reciprocal-estimates" function attribute).
#
# `PTXRSqrtFastPass` must run first: the rsqrt pattern (`fdiv afn 1.0, sqrt afn x`)
# spans an fdiv and a sqrt, so it has to claim both operands before the per-op
# passes below eat them.

# Rewrite `fdiv afn 1.0, sqrt afn(x)` on f64 to `nvvm.rsqrt.approx.d(x)`.
function ptx_rsqrt_fast!(mod::LLVM.Module)
    changed = false
    @tracepoint "ptx-rsqrt-fast" begin

    f64 = LLVM.DoubleType()

    # collect first to avoid mutation-during-iteration
    to_replace = Tuple{LLVM.FDivInst, LLVM.CallInst}[]
    for f in mod.functions, bb in f.blocks, inst in bb.instructions
        inst isa LLVM.FDivInst || continue
        inst.value_type == f64 || continue
        inst.fast_math.afn || continue

        # numerator must be the constant 1.0
        lhs = inst.operands[1]
        lhs isa LLVM.ConstantFP || continue
        convert(Float64, lhs) == 1.0 || continue

        # denominator must be an `afn`-flagged `llvm.sqrt.f64` call
        rhs = inst.operands[2]
        rhs isa LLVM.CallInst || continue
        callee = rhs.called_operand
        callee isa LLVM.Function || continue
        callee.name == "llvm.sqrt.f64" || continue
        rhs.fast_math.afn || continue

        push!(to_replace, (inst, rhs))
    end
    isempty(to_replace) && return false

    # declare intrinsics by name so LLVM keeps the exact non-overloaded names;
    # LLVM.Intrinsic + type params would mangle to *.f64, unrecognized by NVPTX.
    fns = mod.functions
    declare(name, ft) = get!(() -> LLVM.Function(mod, name, ft), fns, name)
    f64_ft = LLVM.FunctionType(f64, [f64])
    rsqrt_f64 = declare("llvm.nvvm.rsqrt.approx.d", f64_ft)

    @dispose builder=IRBuilder() begin
        for (fdiv, sqrt_call) in to_replace
            x = sqrt_call.operands[1]
            position!(builder, LLVM.before(fdiv))

            replacement = call!(builder, f64_ft, rsqrt_f64, [x])

            replace_uses!(fdiv, replacement)
            erase!(fdiv)
            # sqrt may still be used elsewhere; only clean it up if dead now.
            if isempty(sqrt_call.uses)
                erase!(sqrt_call)
            end
            changed = true
        end
    end

    end # @tracepoint
    return changed
end
PTXRSqrtFastPass() = ModulePass("ptx-rsqrt-fast", ptx_rsqrt_fast!)

# Rewrite `afn`-flagged f64 `fdiv` to `rcp.approx.ftz.d` + one Newton step
# (there is no native fast f64 fdiv).
function ptx_fdiv_fast!(mod::LLVM.Module)
    changed = false
    @tracepoint "ptx-fdiv-fast" begin

    f64 = LLVM.DoubleType()

    # collect first to avoid mutation-during-iteration
    to_replace = LLVM.FDivInst[]
    for f in mod.functions, bb in f.blocks, inst in bb.instructions
        inst isa LLVM.FDivInst || continue
        inst.value_type == f64 || continue
        inst.fast_math.afn || continue
        push!(to_replace, inst)
    end
    isempty(to_replace) && return false

    fns = mod.functions
    declare(name, ft) = get!(() -> LLVM.Function(mod, name, ft), fns, name)
    f64_ft1 = LLVM.FunctionType(f64, [f64])
    rcp_f64 = declare("llvm.nvvm.rcp.approx.ftz.d", f64_ft1)
    fma_ft  = LLVM.FunctionType(f64, [f64, f64, f64])
    fma_f64 = declare("llvm.fma.f64", fma_ft)
    one_f64 = ConstantFP(f64, 1.0)

    @dispose builder=IRBuilder() begin
        for inst in to_replace
            lhs, rhs = inst.operands[1], inst.operands[2]
            position!(builder, LLVM.before(inst))

            inv_y   = call!(builder, f64_ft1, rcp_f64, [rhs])
            neg_rhs = fneg!(builder, rhs)
            # Newton refinement, matching CUDA.jl's `FastMath.inv_fast(::Float64)`
            e       = call!(builder, fma_ft, fma_f64, [inv_y, neg_rhs, one_f64])
            e       = call!(builder, fma_ft, fma_f64, [e, e, e])
            inv_ref = call!(builder, fma_ft, fma_f64, [e, inv_y, inv_y])
            replacement = fmul!(builder, lhs, inv_ref)

            replace_uses!(inst, replacement)
            erase!(inst)
            changed = true
        end
    end

    end # @tracepoint
    return changed
end
PTXFDivFastPass() = ModulePass("ptx-fdiv-fast", ptx_fdiv_fast!)

