# Replace occurrences of __nvvm_reflect("foo") and llvm.nvvm.reflect with an integer.
#
# This matches LLVM's NVVMReflectPass: `__CUDA_ARCH` is derived from the target
# capability, `__CUDA_FTZ` is read from the `nvvm-reflect-ftz` module flag, and every
# other key folds to 0. Knobs like denormal flushing or FMAD contraction must be
# configured through module flags or LLVM fast-math flags, not here.
const NVVM_REFLECT_FUNCTION = "__nvvm_reflect"
function nvvm_reflect!(@nospecialize(job::CompilerJob), mod::LLVM.Module)
    changed = false
    @tracepoint "nvvmreflect" begin

    # find and sanity check the nnvm-reflect function
    # TODO: also handle the llvm.nvvm.reflect intrinsic
    reflect_function = get(mod.functions, NVVM_REFLECT_FUNCTION, nothing)
    reflect_function === nothing && return false
    isdeclaration(reflect_function) || error("_reflect function should not have a body")
    reflect_typ = reflect_function.function_type.return_type
    isa(reflect_typ, LLVM.IntegerType) || error("_reflect's return type should be integer")

    # pull __CUDA_FTZ from the nvvm-reflect-ftz module flag (same source LLVM uses)
    ftz_val = 0
    if haskey(mod.flags, "nvvm-reflect-ftz")
        flag = mod.flags["nvvm-reflect-ftz"]
        if flag isa LLVM.ConstantAsMetadata
            c = LLVM.Value(flag)
            if c isa ConstantInt
                ftz_val = Int(convert(Int64, c))
            end
        end
    end

    to_remove = []
    for use in reflect_function.uses
        call = use.user
        isa(call, LLVM.CallInst) || continue
        if length(call.operands) != 2
            @error """Unrecognized format of __nvvm_reflect call:
                      $(string(call))
                      Wrong number of operands: expected 2, got $(length(call.operands))."""
            continue
        end

        # decode the string argument
        if LLVM.version() >= v"17"
            sym = call.operands[1]
        else
            str = call.operands[1]
            if !isa(str, LLVM.ConstantExpr) || str.opcode != LLVM.Opcode.GetElementPtr
                @safe_error """Unrecognized format of __nvvm_reflect call:
                               $(string(call))
                               Operand should be a GEP instruction, got a $(typeof(str)). Please file an issue."""
                continue
            end
            sym = str.operands[1]
            if isa(sym, LLVM.ConstantExpr) && sym.opcode == LLVM.Opcode.GetElementPtr
                # CUDA 11.0 or below
                sym = sym.operands[1]
            end
        end
        if !isa(sym, LLVM.GlobalVariable)
            @safe_error """Unrecognized format of __nvvm_reflect call:
                           $(string(call))
                           Operand should be a global variable, got a $(typeof(sym)). Please file an issue."""
            continue
        end
        sym_op = sym.initializer
        if sym_op === nothing || !isstring(sym_op)
            @safe_error """Unrecognized format of __nvvm_reflect call:
                           $(string(call))
                           Operand should be a constant string, got a $(typeof(sym_op)). Please file an issue."""
            continue
        end
        reflect_arg = chop(String(sym_op))  # without the terminating NUL

        # match LLVM's NVVMReflectPass: unknown keys fold to 0.
        reflect_val = if reflect_arg == "__CUDA_ARCH"
            ConstantInt(reflect_typ,
                        job.config.target.cap.major*100 + job.config.target.cap.minor*10)
        elseif reflect_arg == "__CUDA_FTZ"
            ConstantInt(reflect_typ, ftz_val)
        else
            ConstantInt(reflect_typ, 0)
        end

        replace_uses!(call, reflect_val)
        push!(to_remove, call)
        changed = true
    end

    # remove the calls to the function
    for val in to_remove
        @assert isempty(val.uses)
        erase!(val)
    end

    # maybe also delete the function
    if isempty(reflect_function.uses)
        erase!(reflect_function)
    end

    end
    return changed
end

# The passes below rewrite `afn`-flagged f64 operations to NVPTX' fast lowerings.
# `apply_fastmath!` propagates job-wide `target.fastmath=true` as per-instruction
# `afn`, so a single flag check covers both per-call `@fastmath` and the job toggle.
# We emit NVPTX intrinsics by name (rather than libdevice `__nv_*`) so this doesn't
# depend on which libdevice symbols got linked in.
#
# Only f64 needs this: the back-end natively honors `afn` for f32 fdiv/sqrt/rsqrt
# (selecting the FTZ variants based on the `denormal-fp-math-f32` attribute), but
# lacks fast f64 lowerings. There is no hardware fast f64 div/sqrt, and the f64
# `rsqrt.approx.d` instruction is not selected for `1/sqrt(x)` upstream (NVPTX'
# `getSqrtEstimate` does not consult per-instruction `afn`, only the
# "reciprocal-estimates" function attribute).
#
# `PTXRSqrtFastPass` must run first: the rsqrt pattern (`fdiv afn 1.0, sqrt afn x`)
# spans an fdiv and a sqrt, so it has to claim both operands before the per-op
# passes below eat them.

# Rewrite `fdiv afn 1.0, sqrt afn(x)` on f64 to `nvvm.rsqrt.approx.d(x)`.
function ptx_rsqrt_fast!(mod::LLVM.Module)
    changed = false
    @tracepoint "ptx-rsqrt-fast" begin

    f64 = LLVM.DoubleType()

    # collect first to avoid mutation-during-iteration
    to_replace = Tuple{LLVM.FDivInst, LLVM.CallInst}[]
    for f in mod.functions, bb in f.blocks, inst in bb.instructions
        inst isa LLVM.FDivInst || continue
        inst.value_type == f64 || continue
        inst.fast_math.afn || continue

        # numerator must be the constant 1.0
        lhs = inst.operands[1]
        lhs isa LLVM.ConstantFP || continue
        convert(Float64, lhs) == 1.0 || continue

        # denominator must be an `afn`-flagged `llvm.sqrt.f64` call
        rhs = inst.operands[2]
        rhs isa LLVM.CallInst || continue
        callee = rhs.called_operand
        callee isa LLVM.Function || continue
        callee.name == "llvm.sqrt.f64" || continue
        rhs.fast_math.afn || continue

        push!(to_replace, (inst, rhs))
    end
    isempty(to_replace) && return false

    # declare intrinsics by name so LLVM keeps the exact non-overloaded names;
    # LLVM.Intrinsic + type params would mangle to *.f64, unrecognized by NVPTX.
    fns = mod.functions
    declare(name, ft) = get!(() -> LLVM.Function(mod, name, ft), fns, name)
    f64_ft = LLVM.FunctionType(f64, [f64])
    rsqrt_f64 = declare("llvm.nvvm.rsqrt.approx.d", f64_ft)

    @dispose builder=IRBuilder() begin
        for (fdiv, sqrt_call) in to_replace
            x = sqrt_call.operands[1]
            position!(builder, LLVM.before(fdiv))

            replacement = call!(builder, f64_ft, rsqrt_f64, [x])

            replace_uses!(fdiv, replacement)
            erase!(fdiv)
            # sqrt may still be used elsewhere; only clean it up if dead now.
            if isempty(sqrt_call.uses)
                erase!(sqrt_call)
            end
            changed = true
        end
    end

    end # @tracepoint
    return changed
end
PTXRSqrtFastPass() = ModulePass("ptx-rsqrt-fast", ptx_rsqrt_fast!)

# Rewrite `afn`-flagged f64 `fdiv` to `rcp.approx.ftz.d` + one Newton step
# (there is no native fast f64 fdiv).
function ptx_fdiv_fast!(mod::LLVM.Module)
    changed = false
    @tracepoint "ptx-fdiv-fast" begin

    f64 = LLVM.DoubleType()

    # collect first to avoid mutation-during-iteration
    to_replace = LLVM.FDivInst[]
    for f in mod.functions, bb in f.blocks, inst in bb.instructions
        inst isa LLVM.FDivInst || continue
        inst.value_type == f64 || continue
        inst.fast_math.afn || continue
        push!(to_replace, inst)
    end
    isempty(to_replace) && return false

    fns = mod.functions
    declare(name, ft) = get!(() -> LLVM.Function(mod, name, ft), fns, name)
    f64_ft1 = LLVM.FunctionType(f64, [f64])
    rcp_f64 = declare("llvm.nvvm.rcp.approx.ftz.d", f64_ft1)
    fma_ft  = LLVM.FunctionType(f64, [f64, f64, f64])
    fma_f64 = declare("llvm.fma.f64", fma_ft)
    one_f64 = ConstantFP(f64, 1.0)

    @dispose builder=IRBuilder() begin
        for inst in to_replace
            lhs, rhs = inst.operands[1], inst.operands[2]
            position!(builder, LLVM.before(inst))

            inv_y   = call!(builder, f64_ft1, rcp_f64, [rhs])
            neg_rhs = fneg!(builder, rhs)
            # Newton refinement, matching CUDA.jl's `FastMath.inv_fast(::Float64)`
            e       = call!(builder, fma_ft, fma_f64, [inv_y, neg_rhs, one_f64])
            e       = call!(builder, fma_ft, fma_f64, [e, e, e])
            inv_ref = call!(builder, fma_ft, fma_f64, [e, inv_y, inv_y])
            replacement = fmul!(builder, lhs, inv_ref)

            replace_uses!(inst, replacement)
            erase!(inst)
            changed = true
        end
    end

    end # @tracepoint
    return changed
end
PTXFDivFastPass() = ModulePass("ptx-fdiv-fast", ptx_fdiv_fast!)

