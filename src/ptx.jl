    print(io, "PTX CompilerJob of ", job.source)
    print(io, " for ", cpu_name(job.config.target))
    job.config.target.backend === :nvptx || print(io, " using ", job.config.target.backend)

    job.config.target.minthreads !== nothing && print(io, ", minthreads=$(job.config.target.minthreads)")
    job.config.target.maxthreads !== nothing && print(io, ", maxthreads=$(job.config.target.maxthreads)")
    job.config.target.blocks_per_sm !== nothing && print(io, ", blocks_per_sm=$(job.config.target.blocks_per_sm)")
    job.config.target.maxregs !== nothing && print(io, ", maxregs=$(job.config.target.maxregs)")
    job.config.target.fastmath && print(io, ", fast math enabled")
end

const ptx_intrinsics = ("vprintf", "__assertfail", "malloc", "free")
isintrinsic(@nospecialize(job::CompilerJob{PTXCompilerTarget}), fn::String) =
    in(fn, ptx_intrinsics) ||
    # NVVM intrinsics that the in-process LLVM does not know about, e.g. selected by
    # libdevice's __CUDA_ARCH dispatch, are still supported by the external back-end.
    startswith(fn, "llvm.nvvm.")

function finish_module!(@nospecialize(job::CompilerJob{PTXCompilerTarget}),
                        mod::LLVM.Module, entry::LLVM.Function)
    # tell NVVMReflect whether to flush denormals; this mirrors what Clang does
    # for `-fcuda-flush-denormals-to-zero` and is the only `__nvvm_reflect` key
    # LLVM's NVVMReflectPass honors besides `__CUDA_ARCH`. only emit it on the
    # toplevel module that runs through `optimize!`, as sub-modules (the cached
    # runtime, deferred jobs) don't need it and should not get module-level
    # flags that can collide when linked into the toplevel module.
    if job.config.toplevel
        mod.flags["nvvm-reflect-ftz", LLVM.ModuleFlagBehavior.Override] =
            Metadata(ConstantInt(Int32(job.config.target.fastmath ? 1 : 0)))
    end

    # update calling convention
    for f in mod.functions
        # JuliaGPU/GPUCompiler.jl#97
        #f.callconv = LLVM.CallConv.PTXDevice
    end
    if job.config.kernel
        entry.callconv = LLVM.CallConv.PTXKernel
    end

    if job.config.kernel
        # work around bad byval codegen (JuliaGPU/GPUCompiler.jl#92)
        entry = lower_byval(job, mod, entry)

        # emit kernel property annotations into the module. these have to be in
        # place before optimization runs: LLVM's NVPTX target machine registers a
        # PipelineStart EP callback that schedules NVVMIntrRangePass, which calls
        # `getMaxNTID` on every function. That populates a module-keyed
        # `AnnotationCache` entry (empty, because `nvvm.annotations` isn't there
        # yet), and subsequent lookups by the asm printer hit the stale empty
        # entry instead of re-reading the metadata.
        annotations = Metadata[entry]

        # note that the entry is only marked as a kernel through its ptx_kernel calling
        # convention; the "kernel" nvvm.annotation is redundant (the back-end upgrades
        # it to the calling convention), and on LLVM >= 20 even causes miscompilations.

        # launch bounds are emitted in two forms: as nvvm.annotations metadata, consumed
        # by the in-process LLVM's passes (and auto-upgraded by the back-end), and as
        # function attributes, the form modern LLVM consumes directly.

        # expected CTA sizes
        if job.config.target.minthreads !== nothing
            bounds = ntuple(i -> i <= length(job.config.target.minthreads) ?
                                 job.config.target.minthreads[i] : 1, 3)
            for (bound, name) in zip(bounds, (:x, :y, :z))
                append!(annotations, [MDString("reqntid$name"),
                                      ConstantInt(Int32(bound))])
            end
            push!(entry.function_attributes,
                  StringAttribute("nvvm.reqntid", join(bounds, ",")))
        end
        if job.config.target.maxthreads !== nothing
            bounds = ntuple(i -> i <= length(job.config.target.maxthreads) ?
                                 job.config.target.maxthreads[i] : 1, 3)
            for (bound, name) in zip(bounds, (:x, :y, :z))
                append!(annotations, [MDString("maxntid$name"),
                                      ConstantInt(Int32(bound))])
            end
            push!(entry.function_attributes,
                  StringAttribute("nvvm.maxntid", join(bounds, ",")))
        end

        if job.config.target.blocks_per_sm !== nothing
            append!(annotations, [MDString("minctasm"),
                                  ConstantInt(Int32(job.config.target.blocks_per_sm))])
            push!(entry.function_attributes,
                  StringAttribute("nvvm.minctasm", string(job.config.target.blocks_per_sm)))
        end

        if job.config.target.maxregs !== nothing
            append!(annotations, [MDString("maxnreg"),
                                  ConstantInt(Int32(job.config.target.maxregs))])
            push!(entry.function_attributes,
                  StringAttribute("nvvm.maxnreg", string(job.config.target.maxregs)))
        end

        if length(annotations) > 1
            push!(get!(mod.metadata, "nvvm.annotations").operands, MDNode(annotations))
        end
    end

    return entry
end

function finish_linked_module!(@nospecialize(job::CompilerJob{PTXCompilerTarget}),
                               mod::LLVM.Module)
    # fold `__nvvm_reflect` calls, now that libdevice has been linked. we do this
    # ourselves, and not from the in-process LLVM's NVVMReflectPass (scheduled by the
    # NVPTX TargetMachine's pipeline start callbacks since LLVM 17), because that pass
    # derives `__CUDA_ARCH` from the middle-end subtarget, which cannot represent
    # devices newer than the in-process LLVM. by folding before optimization, at the
    # true target, the built-in pass is left with nothing to do.
    nvvm_reflect!(job, mod)

    # propagate `target.fastmath` as `@fastmath`-everywhere semantics
    # (mirrors nvcc's `--use_fast_math`). post-link so that bodies pulled in
    # from libdevice and the runtime also get the flags.
    if job.config.target.fastmath
        apply_fastmath!(mod)
        # additionally request FTZ on f32: NVPTX' `useF32FTZ` reads
        # `denormal-fp-math-f32` to pick the FTZ variants for
        # fdiv/fsqrt/etc.
        for f in mod.functions
            isdeclaration(f) && continue
            push!(f.function_attributes,
                  StringAttribute("denormal-fp-math-f32",
                                  "preserve-sign,preserve-sign"))
        end
    end
    return
end

finish_imports!(@nospecialize(job::CompilerJob{PTXCompilerTarget}), mod::LLVM.Module,
                imported) = finish_linked_module!(job, mod)

function optimize_module!(@nospecialize(job::CompilerJob{PTXCompilerTarget}),
                          mod::LLVM.Module)
    with_llvm_machine(job.config.target) do tm
        # TODO: Use the registered target passes (JuliaGPU/GPUCompiler.jl#450)
        @dispose pb=PassBuilder() begin
            register!(pb, PTXRSqrtFastPass())
            register!(pb, PTXFDivFastPass())
            register!(pb, PTXFSqrtFastPass())
            if optimization_option(job, :fastmath, true)
                add!(pb, PTXRSqrtFastPass())
                add!(pb, PTXFDivFastPass())
                add!(pb, PTXFSqrtFastPass())
            end

            add!(pb, FunctionPassManager()) do fpm
                # needed by GemmKernels.jl-like code
                add!(fpm, SpeculativeExecutionPass())

                # NVPTX's target machine info enables runtime unrolling,
                # but Julia's pass sequence only invokes the simple unroller.
                add!(fpm, LoopUnrollPass(; job.config.opt_level))
                add!(fpm, instcombine_pass(job))        # clean-up redundancy
                add!(fpm, LoopPassManager(; use_memory_ssa=true)) do lpm
                    add!(lpm, LICMPass())           # the inner runtime check might be
                                                    # outer loop invariant
                end

                # the above loop unroll pass might have unrolled regular, non-runtime nested loops.
                # that code still needs to be optimized (arguably, multiple unroll passes should be
                # scheduled by the Julia optimizer). do so here, instead of re-optimizing entirely.
                if job.config.opt_level == 2
                    add!(fpm, GVNPass())
                elseif job.config.opt_level == 1
                    add!(fpm, EarlyCSEPass())
                end
                add!(fpm, DSEPass())

                add!(fpm, SimplifyCFGPass())
            end

            # get rid of the internalized functions; now possible unused
            add!(pb, GlobalDCEPass())

            run!(pb, mod, tm)
        end
    end
end

function finish_ir!(@nospecialize(job::CompilerJob{PTXCompilerTarget}), mod::LLVM.Module,
                    entry::LLVM.Function)
    # PTX has no atomics on the stack, and NVPTX doesn't legalize them
    lower_local_atomics!(mod)

    return entry
end

# mirrors `NVPTXCompileOptions` from libnvptx.h
struct NVPTXCompileOptions
    cpu::Cstring
    ptx_major::Cuint
    ptx_minor::Cuint
    is_64bit::Cint
    opt_level::Cint
    fma_contraction::Cint
    verbose::Cint
end

@unlocked function mcgen(@nospecialize(job::CompilerJob{PTXCompilerTarget}),
                         mod::LLVM.Module, format=LLVM.CodeGenFileType.Assembly)
    target = job.config.target
    if target.backend === :nvvm
        if format == LLVM.CodeGenFileType.Object
            return nvvm_codegen(job, mod; lto=true)
        end
        return String(nvvm_codegen(job, mod; lto=false))
    end
    if format != LLVM.CodeGenFileType.Assembly
        error("""The NVPTX back-end only emits PTX assembly;
                 object code (LTO-IR) requires the NVVM back-end (`backend=:nvvm`).""")
    end

    if !isavailable(NVPTX_LLVM_Backend_jll) || !NVPTX_LLVM_Backend_jll.is_available()
        error("NVPTX LLVM back-end not loaded; cannot compile to PTX.")
    end
    backend = ExternalBackend(NVPTX_LLVM_Backend_jll.libnvptx, "NVPTX")

    # the back-end derives the triple and datalayout from these options; unlike `llc`,
    # it rejects unknown processors and PTX versions instead of silently falling back.
    # FMA contraction is requested as `-nvptx-fma-level=1` was: match nvcc by leaving
    # eligible multiply-add pairs contractible for ptxas.
    cpu = cpu_name(target)
    ptx = GC.@preserve cpu begin
        options = Ref(NVPTXCompileOptions(Base.unsafe_convert(Cstring, cpu),
                                          target.ptx.major, target.ptx.minor,
                                          Int === Int64, #=opt_level=# 2,
                                          #=fma_contraction=# true, #=verbose=# true))
        external_compile(backend, bitcode(mod), options,
                         "Failed to compile to PTX with the NVPTX back-end")
    end
    return String(ptx)
end


## NVVM back-end

# the options for a job, and the architecture they target
function nvvm_options(@nospecialize(job::CompilerJob{PTXCompilerTarget}))
    target = job.config.target
    arch = replace(cpu_name(target), "sm_" => "compute_")

    # earlier versions ignore the synchronization scope and ordering of `atomicrmw`
    if NVVM.toolkit_version() < v"13.5"
        error("""The NVVM back-end requires libNVVM from CUDA 13.5 or later.
                 Earlier versions miscompile atomic operations.""")
    end

    # libNVVM reads bitcode from LLVM 7 for older architectures, unless `-nvvm-latest`
    # selects its current LLVM, which Blackwell and later use by default
    options = ["-arch=$arch"]
    reader = NVVM.llvm_version(arch)
    if reader === nothing
        error("libNVVM does not support $arch.")
    elseif reader < LLVM.version().major
        push!(options, "-nvvm-latest")
    end

    # options that tune libNVVM's passes (`-Xopt`, `-Xllc`, `-aggressive-inline`, ...) must
    # never be passed here: libNVVM keeps them for the rest of the process, so they would
    # leak into the compilation of every later job.

    # libNVVM only flushes f32 denormals, as fast math does, when asked to for the whole
    # module (approximate division and square roots are selected by `lower_approx_math!`)
    if target.fastmath
        append!(options, ["-ftz=1", "-prec-div=0", "-prec-sqrt=0"])
    end

    # the debug info itself comes from the module's metadata (see `llvm_debug_info`), so
    # these flags only mirror what `nvcc -lineinfo` and `nvcc -G` pass to libNVVM's `cicc`.
    # unlike `-G`, we don't add `-opt=0`: NVPTX also emits debug info for optimized code.
    if job.config.debug_level == 1
        push!(options, "-generate-line-info")
    elseif job.config.debug_level >= 2
        push!(options, "-g")
    end
    return options, arch
end

function nvvm_codegen(@nospecialize(job::CompilerJob{PTXCompilerTarget}), mod::LLVM.Module;
                      lto::Bool)
    if job.config.optimize && job.config.opt_level >= 1
        optimize_nvvm!(mod)
    end
    legalize_nvvm!(mod; lto)
    options, arch = nvvm_options(job)
    lto && push!(options, "-gen-lto")

    input = bitcode(mod)
    prog = NVVM.Program()
    output = try
        NVVM.add!(prog, input)
        NVVM.compile(prog, options)
    catch err
        err isa NVVM.NVVMError || rethrow()
        path, = dump_failure(".bc" => input)
        error(sprint(showerror, err) *
              "\nIf you think this is a bug, please file an issue and attach $(path).")
    finally
        finalize(prog)
    end

    if !lto
        # libNVVM silently turns calls to intrinsics it doesn't know into calls to external
        # functions, which then fail to link
        unknown = unique(m.captures[1] for m in eachmatch(r"\.extern \.func[^\n]*?\b(llvm\.[\w.]+)",
                                                         String(copy(output))))
        if !isempty(unknown)
            path, = dump_failure(".bc" => input)
            error("libNVVM does not support the intrinsics $(join(unknown, ", ")).\n" *
                  "If you think this is a bug, please file an issue and attach $(path).")
        end
    end

    return output
end

# Julia's loops typically have bounds checks, which add an exit to `noreturn` error
# reporting code. In loops with such an extra exit, libNVVM can keep computing the address
# from the induction variable (`base + i * stride`, a 64-bit multiply) in every iteration,
# where NVPTX's code generator strength-reduces it into an incremented pointer. Running
# LLVM's loop strength reduction before libNVVM recovers that. Without NVPTX's target
# machine it uses LLVM's default cost model, which measured as a net win.
#
# IR sinking would gain a few percent more on some kernels, but is deliberately not run: it
# can move many instructions into the join after a branch (e.g. an inlined `sin` with a slow
# path), keeping their operands live across both paths, and raise register use enough that
# launches of large blocks that work with NVPTX fail.
function optimize_nvvm!(mod::LLVM.Module)
    @dispose pb=PassBuilder() begin
        add!(pb, FunctionPassManager()) do fpm
            add!(fpm, LoopPassManager()) do lpm
                add!(lpm, LoopStrengthReducePass())
            end
        end
        run!(pb, mod)
    end
    return mod
end

# make a module acceptable to libNVVM, which otherwise accepts the same IR as NVPTX
function legalize_nvvm!(mod::LLVM.Module; lto::Bool=false)
    lower_approx_math!(mod)

    # libNVVM requires a version, which libraries like libdevice carry, possibly repeatedly.
    # a module with debug info also needs the version of the debug metadata, or libNVVM
    # rejects it as soon as it's asked to emit debug info (`-g`, `-generate-line-info`).
    versions = get!(mod.metadata, "nvvmir.version")
    if haskey(mod.metadata, "llvm.dbg.cu") && !isempty(mod.metadata["llvm.dbg.cu"].operands)
        (; ir, dbg) = NVVM.ir_version()
        empty!(versions.operands)
        push!(versions.operands,
              MDNode(Metadata[ConstantInt(Int32(ir.major)), ConstantInt(Int32(ir.minor)),
                              ConstantInt(Int32(dbg.major)), ConstantInt(Int32(dbg.minor))]))
    elseif isempty(versions.operands)
        push!(versions.operands,
              MDNode(Metadata[ConstantInt(Int32(2)), ConstantInt(Int32(0))]))
    end

    # NVIDIA's compilers declare the debug metadata version with the `Error` behavior, and
    # nvJitLink refuses to link modules whose flags have different behaviors, so LTO-IR
    # with Julia's `Warning` couldn't be linked with code from NVRTC or nvcc
    if haskey(mod.metadata, "llvm.module.flags")
        flags = mod.metadata["llvm.module.flags"].operands
        updated = map(collect(flags)) do flag
            _, key, val = flag.operands
            String(key) == "Debug Info Version" || return flag
            MDNode(Metadata[ConstantInt(Int32(1)), key, val]) # 1 = Error
        end
        empty!(flags)
        foreach(flag -> push!(flags, flag), updated)
    end

    # nvJitLink links LTO-IR as a whole program, dropping everything that isn't used,
    # including kernels that aren't referenced
    if lto
        kernels = filter(f -> f.callconv == LLVM.CallConv.PTXKernel, collect(mod.functions))
        union!(mod.used, kernels)
    end
    return mod
end

function llvm_debug_info(@nospecialize(job::CompilerJob{PTXCompilerTarget}))
    # allow overriding the debug info from CUDA.jl
    if job.config.target.debuginfo
        invoke(llvm_debug_info, Tuple{CompilerJob}, job)
