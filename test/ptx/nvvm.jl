@testset "LTO-IR" begin
    job, _ = PTX.create_job(mod.kernel, Tuple{Ptr{Float32},Float32};
                            backend=:nvvm, cap=v"10.0", kernel=true)
    ltoir = JuliaContext() do ctx
        ltoir, meta = GPUCompiler.compile(:obj, job)
        LLVM.dispose(meta.ir)
        ltoir
    end
    @test ltoir isa Vector{UInt8}
    @test ltoir[1:4] == [0xed, 0x43, 0x4e, 0x7f]

    # linking keeps the kernel, which nothing else references
    @test occursin(".entry", nvjitlink_ptx(ltoir, "-arch=sm_100"))

    # LTO-IR for older architectures needs nvJitLink to use the current reader too
    if CUDA_Compiler_jll.cuda_version >= v"13.5"
        job, _ = PTX.create_job(mod.kernel, Tuple{Ptr{Float32},Float32};
                                backend=:nvvm, cap=v"7.5", kernel=true)
        ltoir = JuliaContext() do ctx
            ltoir, meta = GPUCompiler.compile(:obj, job)
            LLVM.dispose(meta.ir)
            ltoir
        end
        @test occursin(".entry", nvjitlink_ptx(ltoir, "-arch=sm_75", "-nvvm-latest"))
    end

    job, _ = PTX.create_job(mod.kernel, Tuple{Ptr{Float32},Float32}; kernel=true)
    JuliaContext() do ctx
        @test_throws "requires the NVVM back-end" GPUCompiler.compile(:obj, job)
    end
end

@testset "fast math" begin
    # libNVVM ignores `afn`, so the approximate instructions are selected before
    mod = @eval module $(gensym())
        sqrt_fast(ptr, x) = (unsafe_store!(ptr, @fastmath sqrt(x)); nothing)
        div_fast(ptr, x, y) = (unsafe_store!(ptr, @fastmath x / y); nothing)
        inv_fast(ptr, x) = (unsafe_store!(ptr, @fastmath 1f0 / x); nothing)
        rsqrt_fast(ptr, x) = (unsafe_store!(ptr, @fastmath 1f0 / sqrt(x)); nothing)
    end
    for (f, types, instr) in ((mod.sqrt_fast, Tuple{Ptr{Float32},Float32}, "sqrt"),
                              (mod.div_fast, Tuple{Ptr{Float32},Float32,Float32}, "div"),
                              (mod.inv_fast, Tuple{Ptr{Float32},Float32}, "rcp"),
                              (mod.rsqrt_fast, Tuple{Ptr{Float32},Float32}, "rsqrt"))
        @test @filecheck begin
            @check "$instr.approx.f32"
            @check_not "{{(rcp|sqrt|div).approx}}"
            PTX.code_native(f, types; backend=:nvvm, cap=v"10.0")
        end
        @test @filecheck begin
            @check "$instr.approx.ftz.f32"
            @check_not "{{(rcp|sqrt|div).approx}}"
            PTX.code_native(f, types; backend=:nvvm, cap=v"10.0", fastmath=true)
        end
    end
end

@testset "fast math on vectors" begin
    mod = @eval module $(gensym())
        const V = NTuple{2,VecElement{Float32}}
        div_fast(ptr, x, y) = unsafe_store!(ptr, Base.llvmcall("""
            %r = fdiv afn <2 x float> %0, %1
            ret <2 x float> %r""", V, Tuple{V,V}, x, y))
        rsqrt_fast(ptr, x) = unsafe_store!(ptr, Base.llvmcall("""
            %s = call afn <2 x float> @llvm.sqrt.v2f32(<2 x float> %0)
            %r = fdiv afn <2 x float> <float 1.0, float 1.0>, %s
            ret <2 x float> %r""", V, Tuple{V}, x))
    end
    @test @filecheck begin
        @check "div.approx.f32"
        @check "div.approx.f32"
        PTX.code_native(mod.div_fast, Tuple{Ptr{mod.V},mod.V,mod.V}; backend=:nvvm, cap=v"10.0")
    end
    @test @filecheck begin
        @check "rsqrt.approx.f32"
        @check "rsqrt.approx.f32"
        @check_not "{{(rcp|[^r]sqrt|div).approx}}"
        PTX.code_native(mod.rsqrt_fast, Tuple{Ptr{mod.V},mod.V}; backend=:nvvm, cap=v"10.0")
    end
end

@testset "fast math across blocks" begin
    # the square root is defined in a block laid out after the reciprocal using it
    Context() do ctx
        ir = parse(LLVM.Module, """
            define void @kernel(ptr %p, float %x) {
            entry:
              br label %def
            use:
              %r = fdiv afn float 1.0, %s
              store float %r, ptr %p
              ret void
            def:
              %s = call afn float @llvm.sqrt.f32(float %x)
              br label %use
            }
            declare float @llvm.sqrt.f32(float)""")
        @test GPUCompiler.lower_approx_math!(ir)
        str = string(ir)
        @test occursin("call float @llvm.nvvm.rsqrt.approx.f(float %x)", str)
        @test !occursin("call afn float @llvm.sqrt.f32", str)
        @test !occursin("llvm.nvvm.sqrt.approx", str)
        @test !occursin("llvm.nvvm.rcp.approx", str)
    end
end

@testset "loops with bounds checks" begin
    # libNVVM's code generator doesn't strength-reduce loops that exit through bounds checks
    # like NVPTX's does (see `optimize_nvvm!`)
    mod = @eval module $(gensym())
        # strided accesses: the address is a multiplication of the induction variable
        function strided(out::Ptr{Float32}, a::Ptr{Float32}, stride::Int, n::Int, len::Int)
            acc = 0f0
            for i in 1:n
                idx = (i - 1) * stride + 1
                idx <= len || throw(BoundsError())
                acc += unsafe_load(a, idx)
            end
            unsafe_store!(out, acc)
            return
        end
    end

    # the address is incremented by the stride instead of recomputed, with or without
    # a multiply-add: the kernel has no other integer multiplications
    @test @filecheck begin
        @check_label ".entry"
        @check_not "{{(mul|mad)\\.(lo|wide)}}"
        @check "ret;"
        PTX.code_native(mod.strided, Tuple{Ptr{Float32},Ptr{Float32},Int,Int,Int};
                        backend=:nvvm, cap=v"10.0", kernel=true)
    end
end

@testset "older architectures" begin
    # libNVVM only reads current bitcode for these with `-nvvm-latest`, added in CUDA 13.5
    if CUDA_Compiler_jll.cuda_version >= v"13.5"
        @test @filecheck begin
            @check ".target sm_75"
            @check ".visible .entry"
            PTX.code_native(mod.kernel, Tuple{Ptr{Float32},Float32};
                            backend=:nvvm, cap=v"7.5", kernel=true)
        end
    else
        @test_throws "requires CUDA 13.5 or later" PTX.code_native(devnull, mod.kernel,
            Tuple{Ptr{Float32},Float32}; backend=:nvvm, cap=v"7.5")
    end
end

