# libNVVM before CUDA 13.5 miscompiles atomics
if NVVM.is_available() && NVVM.toolkit_version() < v"13.5"
    @testset "toolkit requirement" begin
        f(ptr) = (unsafe_store!(ptr, 1f0); nothing)
        @test_throws "requires libNVVM from CUDA 13.5 or later" PTX.code_native(devnull, f,
            Tuple{Ptr{Float32}}; backend=:nvvm)
    end
end

if !PTX.nvvm_available()
    @warn "libNVVM from CUDA 13.5+ not available; skipping NVVM tests"
else

mod = @eval module $(gensym())
    function kernel(ptr, x)
        unsafe_store!(ptr, x * x + 1f0)
        return
    end
end

# link LTO-IR with nvJitLink, returning the PTX it generates
function nvjitlink_ptx(ltoir, options...)
    lib = CUDA_Compiler_jll.libnvJitLink
    version = "$(CUDA_Compiler_jll.cuda_version.major)_0"
    api(name) = Libc.Libdl.dlsym(Libc.Libdl.dlopen(lib), Symbol("__nvJitLink$(name)_$version"))
    handle = Ref{Ptr{Cvoid}}()
    options = ["-lto", "-ptx", options...]
    @test 0 == @ccall $(api("Create"))(handle::Ptr{Ptr{Cvoid}}, length(options)::Cuint,
                                         options::Ptr{Cstring})::Cint
    try
        @test 0 == @ccall $(api("AddData"))(handle[]::Ptr{Cvoid}, 3::Cint, # LTO-IR
                                              ltoir::Ptr{UInt8}, length(ltoir)::Csize_t,
                                              "kernel"::Cstring)::Cint
        @test 0 == @ccall $(api("Complete"))(handle[]::Ptr{Cvoid})::Cint
        size = Ref{Csize_t}()
        @ccall $(api("GetLinkedPtxSize"))(handle[]::Ptr{Cvoid}, size::Ptr{Csize_t})::Cint
        ptx = Vector{UInt8}(undef, size[])
        @ccall $(api("GetLinkedPtx"))(handle[]::Ptr{Cvoid}, ptx::Ptr{UInt8})::Cint
        return String(ptx)
    finally
        @ccall $(api("Destroy"))(handle::Ptr{Ptr{Cvoid}})::Cint
    end
end

@testset "PTX" begin
    @test @filecheck begin
        @check "Generated by NVIDIA NVVM Compiler"
        @check ".target sm_100"
        @check ".visible .entry"
        PTX.code_native(mod.kernel, Tuple{Ptr{Float32},Float32};
                        backend=:nvvm, cap=v"10.0", kernel=true)
    end
end

@testset "datalayout" begin
    @test @filecheck begin
        @check "target datalayout = \"$(GPUCompiler.nvvm_datalayout())\""
        PTX.code_llvm(mod.kernel, Tuple{Ptr{Float32},Float32};
                      backend=:nvvm, cap=v"10.0", dump_module=true)
    end
end

@testset "LTO-IR" begin
    job, _ = PTX.create_job(mod.kernel, Tuple{Ptr{Float32},Float32};
                            backend=:nvvm, cap=v"10.0", kernel=true)
    ltoir = JuliaContext() do ctx
        ltoir, meta = GPUCompiler.compile(:obj, job)
        LLVM.dispose(meta.ir)
        ltoir
    end
    @test ltoir isa Vector{UInt8}
    @test ltoir[1:4] == [0xed, 0x43, 0x4e, 0x7f]

    # linking keeps the kernel, which nothing else references
    @test occursin(".entry", nvjitlink_ptx(ltoir, "-arch=sm_100"))

    # LTO-IR for older architectures needs nvJitLink to use the current reader too
    job, _ = PTX.create_job(mod.kernel, Tuple{Ptr{Float32},Float32};
                            backend=:nvvm, cap=v"7.5", kernel=true)
    ltoir = JuliaContext() do ctx
        ltoir, meta = GPUCompiler.compile(:obj, job)
        LLVM.dispose(meta.ir)
        ltoir
    end
    @test occursin(".entry", nvjitlink_ptx(ltoir, "-arch=sm_75", "-nvvm-latest"))

    job, _ = PTX.create_job(mod.kernel, Tuple{Ptr{Float32},Float32}; kernel=true)
    JuliaContext() do ctx
        @test_throws "requires the NVVM back-end" GPUCompiler.compile(:obj, job)
    end
end

@testset "fast math across blocks" begin
    # the square root is defined in a block laid out after the reciprocal using it
    Context() do ctx
        ir = parse(LLVM.Module, """
            define void @kernel(float* %p, float %x) {
            entry:
              br label %def
            use:
              %r = fdiv afn float 1.0, %s
              store float %r, float* %p
              ret void
            def:
              %s = call afn float @llvm.sqrt.f32(float %x)
              br label %use
            }
            declare float @llvm.sqrt.f32(float)""")
        @test GPUCompiler.lower_approx_math!(ir)
        str = string(ir)
        @test occursin("call float @llvm.nvvm.rsqrt.approx.f(float %x)", str)
        @test !occursin("call afn float @llvm.sqrt.f32", str)
        @test !occursin("llvm.nvvm.sqrt.approx", str)
        @test !occursin("llvm.nvvm.rcp.approx", str)
    end
end

@testset "older architectures" begin
